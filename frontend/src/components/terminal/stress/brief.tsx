import { Printer } from "lucide-react";

import type { ProvenanceSource, Scenario, StressResult } from "@/api/types";
import { formatCurrency, formatDateTime, formatPct } from "@/lib/format";
import { useSettings } from "@/lib/settings";
import { EmptyState, Panel } from "@/components/terminal/kit";

export function NarrativeCard({
  r,
  scenario,
  source,
}: {
  r: StressResult | undefined;
  scenario: Scenario | undefined;
  source: ProvenanceSource | undefined;
}) {
  const { tz } = useSettings();
  return (
    <>
      <Panel
        title="Risk narrative"
        info="Plain-language explanation of the latest stress run, generated by the API from the run's numbers."
        source={source}
        actions={
          <button
            type="button"
            disabled={!r}
            onClick={() => window.print()}
            className="no-print inline-flex items-center gap-1.5 rounded-sm border border-hairline px-2 py-1 text-xs outline-none hover:border-primary hover:text-primary focus-visible:ring-1 focus-visible:ring-ring disabled:opacity-50"
          >
            <Printer className="size-3" /> Export risk brief (PDF)
          </button>
        }
      >
        {r ? (
          <p className="max-w-3xl whitespace-pre-line text-[13px] leading-relaxed">{r.narrative}</p>
        ) : (
          <EmptyState title="Run a scenario to see the impact on the book" />
        )}
      </Panel>
      {r ? <PrintBrief r={r} scenario={scenario} tz={tz} /> : null}
    </>
  );
}

function PrintBrief({
  r,
  scenario,
  tz,
}: {
  r: StressResult;
  scenario: Scenario | undefined;
  tz: "UTC" | "local";
}) {
  const delta = r.valueAfter - r.valueBefore;
  return (
    <div className="print-brief hidden print:block" style={{ fontSize: 12 }}>
      <h1 style={{ fontSize: 20, fontWeight: 600 }}>SENTINEL Stress Risk Brief</h1>
      <p>
        {formatDateTime(r.ts, tz)} ({tz === "UTC" ? "UTC" : "local time"})
      </p>
      <p>
        Scenario: {scenario?.name ?? r.scenarioId} — mode: {r.mode}
      </p>
      <h2 style={{ marginTop: 12, fontWeight: 600 }}>Impact</h2>
      <table style={{ borderCollapse: "collapse", width: "100%" }}>
        <tbody>
          <Row k="Value before" v={formatCurrency(r.valueBefore)} />
          <Row k="Value after" v={formatCurrency(r.valueAfter)} />
          <Row
            k="Delta"
            v={`${formatCurrency(delta)} (${r.valueBefore !== 0 ? formatPct(delta / r.valueBefore, 2, true) : "—"})`}
          />
          <Row
            k="VaR before / after"
            v={`${formatCurrency(r.varBefore)} / ${formatCurrency(r.varAfter)}`}
          />
          <Row
            k="Expected Shortfall before / after"
            v={`${formatCurrency(r.esBefore)} / ${formatCurrency(r.esAfter)}`}
          />
        </tbody>
      </table>
      <h2 style={{ marginTop: 12, fontWeight: 600 }}>Narrative</h2>
      <p style={{ whiteSpace: "pre-line" }}>{r.narrative}</p>
      <h2 style={{ marginTop: 12, fontWeight: 600 }}>By risk factor</h2>
      <table style={{ borderCollapse: "collapse", width: "100%" }}>
        <tbody>
          {r.byFactor.map((f) => (
            <Row key={f.factor} k={f.factor} v={formatCurrency(f.delta)} />
          ))}
        </tbody>
      </table>
      <h2 style={{ marginTop: 12, fontWeight: 600 }}>By asset class (before / after)</h2>
      <table style={{ borderCollapse: "collapse", width: "100%" }}>
        <tbody>
          {r.byAssetClass.map((a) => (
            <Row
              key={a.assetClass}
              k={a.assetClass}
              v={`${formatCurrency(a.before)} / ${formatCurrency(a.after)}`}
            />
          ))}
        </tbody>
      </table>
    </div>
  );
}

function Row({ k, v }: { k: string; v: string }) {
  return (
    <tr>
      <td style={{ border: "1px solid #ccc", padding: "3px 6px" }}>{k}</td>
      <td style={{ border: "1px solid #ccc", padding: "3px 6px", textAlign: "right" }}>{v}</td>
    </tr>
  );
}
